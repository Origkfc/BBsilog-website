const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync('files/review-model.js', 'utf8'), context);
const model = context.window.BBSILOGReviewModel;
const imported = { source: 'messenger_import', owner_publication_approved: true, publish_consent: false, status: 'approved', rating: null, archived_at: null };
assert.equal(model.mayFeature(imported), true);
assert.equal(model.ratingLabel(imported).includes('★'), false, 'Unrated screenshots must never become invented star ratings.');
assert.equal(model.matchesFilter(imported, 'approved'), true);
assert.equal(model.matchesFilter(imported, 'private'), false);
assert.equal(model.matchesFilter(imported, 'imported'), true);
const archived = { ...imported, status: 'pending', archived_at: '2026-10-30T00:00:00Z' };
assert.equal(model.matchesFilter(archived, 'archived'), true);
assert.equal(model.matchesFilter(archived, 'all'), false);
assert.equal(model.matchesFilter(archived, 'approved'), false);
const restored = { ...archived, archived_at: null };
assert.equal(model.matchesFilter(restored, 'pending'), true, 'Restored imports require approval again.');
assert.equal(model.matchesFilter(restored, 'approved'), false);
const privateWebsite = { source: 'website', publish_consent: false, owner_publication_approved: true, status: 'pending', rating: 4 };
assert.equal(model.mayFeature(privateWebsite), false, 'An owner flag must not override a website visitor withholding consent.');
assert.equal(model.matchesFilter(privateWebsite, 'private'), true);
assert.equal(model.matchesFilter(privateWebsite, 'pending'), false);
assert.equal(model.ratingLabel(privateWebsite), '★★★★');
assert.equal(model.mayFeature({ ...imported, owner_publication_approved: false }), false);
console.log('Review model: unrated imports, consent, moderation, archive, and restore checks passed.');
